// ── Helpers ─────────────────────────────────────────────────────────────────

export function getGovernorateById(id: string): Governorate | undefined {
  return EGYPT_GOVERNORATES.find((g) => g.id === id);
}

export function getGovernoratesByRegion(region: string): Governorate[] {
  return EGYPT_GOVERNORATES.filter((g) => g.region === region);
}

export function getRegionalAdjustment(governorateId: string): number {
  const gov = getGovernorateById(governorateId);
  return gov?.regionalAdjustment ?? 1.0;
}

