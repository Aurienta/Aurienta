// ── Helpers ────────────────────────────────────────────────────────────────────

export function getBenchmarkBySector(sectorId: string): FeasibilityBenchmark | undefined {
  return FEASIBILITY_BENCHMARKS.find((b) => b.sectorId === sectorId);
}

export function getBenchmarksByGrowthRate(minGrowthPct: number): FeasibilityBenchmark[] {
  return FEASIBILITY_BENCHMARKS.filter((b) => b.marketGrowthPct >= minGrowthPct);
}

export function getHighMarginSectors(minMarginPct: number): FeasibilityBenchmark[] {
  return FEASIBILITY_BENCHMARKS.filter((b) => b.avgNetMarginPct >= minMarginPct);
}

export function getBenchmarksByPayback(maxYears: number): FeasibilityBenchmark[] {
  return FEASIBILITY_BENCHMARKS.filter((b) => b.avgPaybackYears <= maxYears);
}

export function getBenchmarksByCapitalRange(minEgp: number, maxEgp: number): FeasibilityBenchmark[] {
  return FEASIBILITY_BENCHMARKS.filter(
    (b) => b.startupCapitalMinEgp <= maxEgp && b.startupCapitalMaxEgp >= minEgp,
  );
}

// ── Aggregate Stats ────────────────────────────────────────────────────────────

function mean(arr: number[]): number {
  return arr.length > 0 ? arr.reduce((s, x) => s + x, 0) / arr.length : 0;
}

