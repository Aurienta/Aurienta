//   - Free Zones & QIZ (Qualifying Industrial Zones) regime
//
// Sources (cited per sector):
//   - CAPMAS (Central Agency for Public Mobilization & Statistics)
//   - CBE Annual Report 2023/2024 + Monetary Policy statements
//   - Ministry of Planning & Economic Development —Egypt Vision 2030
//   - GAFI (General Authority for Investment) sectoral reports
//   - Federation of Egyptian Industries (FEI) chamber reports
//   - EGX-listed company financial disclosures (FY2023)
//   - IDA (Industrial Development Authority) industrial land reports
//   - MCIT (Ministry of Communications & Information Technology)
//   - ITIDA (Information Technology Industry Development Agency)
//   - USAID Egypt / MIT sector competitiveness studies (2009–2015)
//   - World Bank Enterprise Surveys (Egypt 2020)
//   - IFC Egypt sector briefs
//   - IMF Article IV Consultations (Egypt)
//   - UNIDO Industrial Statistics
//   - Egyptian Ministry of Tourism statistics
//   - McKinsey / PwC / Deloitte Egypt sector outlooks
